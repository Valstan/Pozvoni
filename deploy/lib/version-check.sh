#!/usr/bin/env bash
# Сторож версии `next` на боевом боксе.
#
# Зачем он нужен. 19.11 закрыт advisory GHSA-2464-fhr4-w9xw (неаутентифицированный RCE в
# API оптимизации изображений, CVE-2026-96889): уязвимая ветка `16.0.0 … 16.4.0`, лечится
# 16.4.1. Версия `next` живёт не в коде, а в релизном пакете на боксе, и **никто её оттуда не
# читал**: «выкачено» означало «собрано из коммита», а коммит мог быть старым (как и вышло —
# уязвимая сборка пролежала на боксе 18 дней). Этот сторож читает версию ИЗ РЕЛИЗА на боксе и
# сравнивает с полом.
#
# Пол — константа, а не версия из `package-lock.json`: иначе понижение `next` в
# `package.json` тихо опустило бы пол вместе с собой, и дыра вернулась бы незамеченной.
#
# Файл приходит на бокс вместе с пробой (конкатенация в workflow), потому что на боксе нет
# репозитория. Поэтому же вынесен отдельным файлом: логику сравнения надо проверять гейтом
# без бокса — `deploy/tests/version-check-logic.test.sh`.
#
# Что НЕ проверяется: что на боксе реально запущен этот релиз, а не старый из-под
# симлинка. Проба смотрит `current` — тот симлинк, который переключает выкатка.

# Пол безопасной версии: 16.4.1 — первая без advisory GHSA-2464-fhr4-w9xw.
MIN_NEXT_VERSION="16.4.1"

# version_ge A B — истина, если версия A не меньше B.
#
# Сравнение по числам, а не по строкам: «16.4.10» обязано быть больше «16.4.9».
# Хвост-пререлиз учитывается по правилам semver: «16.4.2-canary» НОВЕЕ «16.4.1» (числа
# сравниваются по ведущим цифрам), а «16.4.1-canary» СТАРШЕ «16.4.1» — пререлиз идёт
# раньше релиза. Второе сделано fail-closed: пререлиз релизной ветки может быть собран до
# того, как в ветку влили исправление, и доказать обратное на боксе нечем — красный
# честнее зелёного.
version_ge() {
  local a="$1" b="$2"
  [ -n "$a" ] && [ -n "$b" ] || return 1
  [ "$a" = "$b" ] && return 0
  local -a a_parts b_parts
  IFS='.' read -r -a a_parts <<<"$a"
  IFS='.' read -r -a b_parts <<<"$b"
  local i ai bi a_tail=0 b_tail=0
  for i in 0 1 2; do
    ai="${a_parts[$i]:-0}"
    bi="${b_parts[$i]:-0}"
    # Ведущие цифры — число; остаток хвоста помечаем.
    case "$ai" in
      *[!0-9]*) a_tail=1; ai="${ai%%[!0-9]*}" ;;
    esac
    case "$bi" in
      *[!0-9]*) b_tail=1; bi="${bi%%[!0-9]*}" ;;
    esac
    ai="${ai:-0}"
    bi="${bi:-0}"
    [ "$ai" -gt "$bi" ] && return 0
    [ "$ai" -lt "$bi" ] && return 1
  done
  # Числа равны: пререлиз младше релиза.
  [ "$a_tail" -eq 1 ] && [ "$b_tail" -eq 0 ] && return 1
  return 0
}

# Версия `next` из релиза на боксе (пусто, если файла нет).
deployed_next_version() {
  local app_dir="$1"
  local file="$app_dir/current/node_modules/next/package.json"
  [ -f "$file" ] || return 1
  # Версия лежит в поле "version"; разбираем её без node — на боксе node есть, но правило
  # должно работать и в стенде, где файла с node нет.
  sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$file" | head -1
}

# check_deployed_next_version APP_DIR — читает версию из релиза и сравнивает с полом.
# Печатает строку в формате пробы и возвращает 0 (в порядке) или 1 (поломка).
check_deployed_next_version() {
  local app_dir="${1:?не задан каталог приложения}"
  local want="${MIN_NEXT_VERSION}"
  local got
  if ! got="$(deployed_next_version "$app_dir")" || [ -z "$got" ]; then
    # Диагностика — в stdout, а не в stderr: вызывающий workflow глушит stderr ssh целиком
    # (там имя хоста и порт), и сообщение о поломке исчезло бы вместе с чужим.
    echo "  версия next в релизе не читается — версию с бокса нечем подтвердить"
    return 1
  fi
  if version_ge "$got" "$want"; then
    echo "  версия next $got (пол $want)"
    return 0
  fi
  echo "  версия next $got — ниже пола $want (уязвимая сборка на боксе)"
  return 1
}

# Отдельный запуск — для стенда и для ручной проверки с бокса.
if [ "${BASH_SOURCE[0]:-}" = "${0}" ]; then
  check_deployed_next_version "${1:?не задан каталог приложения}"
fi
