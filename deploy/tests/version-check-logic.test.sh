#!/usr/bin/env bash
# Логика сторожа версии `next` (deploy/lib/version-check.sh) — на подставном релизе, без бокса.
#
# Зачем гонять здесь. Проба на боевом боксе — это алертинг проекта, и ошибка в её логике
# выглядит двояко: либо красный прогон без причины (учит игнорировать красный цвет), либо
# зелёный прогон при уязвимой сборке на боксе (то есть дыра, которую закрыли, тихо вернулась).
# Поэтому сравнение версий проверяется тут, на файловых заготовках.
#
# Кейсы: сравнение (равно, больше, меньше, по частям, с нечисловым хвостом), чтение версии
# из релиза и три исхода проверки — в порядке, ниже пола, файл не читается.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SRC="$REPO/deploy/lib/version-check.sh"
[ -f "$SRC" ] || { echo "нет $SRC"; exit 1; }

# shellcheck source=../lib/version-check.sh
. "$SRC"

fail=0
eq() { # <получено> <ожидалось> <что>
  if [ "$1" = "$2" ]; then
    printf 'ok   %s\n' "$3"
  else
    printf 'FAIL %s: получено %s, ожидалось %s\n' "$3" "$1" "$2"
    fail=$((fail + 1))
  fi
}

# ── сравнение версий ───────────────────────────────────────────────────────────────────
version_ge "16.4.1" "16.4.1" && r=0 || r=1; eq "$r" "0" "сравнение: равные версии — не меньше"
version_ge "16.4.6" "16.4.1" && r=0 || r=1; eq "$r" "0" "сравнение: новее — не меньше"
version_ge "16.3.5" "16.4.1" && r=0 || r=1; eq "$r" "1" "сравнение: старее — меньше"
version_ge "16.4.10" "16.4.9" && r=0 || r=1; eq "$r" "0" "сравнение: по числам, а не по строкам (10 > 9)"
version_ge "16.4.9" "16.4.10" && r=0 || r=1; eq "$r" "1" "сравнение: 9 < 10"
version_ge "17.0.0" "16.4.1" && r=0 || r=1; eq "$r" "0" "сравнение: другой минор — больше"
version_ge "16.4" "16.4.0" && r=0 || r=1; eq "$r" "0" "сравнение: короткая версия — не меньше полной"
version_ge "16.4.2-canary" "16.4.1" && r=0 || r=1; eq "$r" "0" "сравнение: пререлиз новее релиза (16.4.2-canary > 16.4.1)"
version_ge "16.4.1-canary" "16.4.1" && r=0 || r=1; eq "$r" "1" "сравнение: пререлиз младше релиза (fail-closed: 16.4.1-canary < 16.4.1)"
version_ge "" "16.4.1" && r=0 || r=1; eq "$r" "1" "сравнение: пустая версия — не больше"
version_ge "16.4.1" "" && r=0 || r=1; eq "$r" "1" "сравнение: пустой пол — не больше"

# ── чтение версии из релиза ───────────────────────────────────────────────────────────
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/app/current/node_modules/next"
printf '{ "name": "next", "version": "16.4.6" }\n' > "$T/app/current/node_modules/next/package.json"

got="$(deployed_next_version "$T/app")"
eq "$got" "16.4.6" "чтение: версия достаётся из релиза"

mkdir -p "$T/empty/current/node_modules"
if deployed_next_version "$T/empty" >/dev/null 2>&1; then r=0; else r=1; fi
eq "$r" "1" "чтение: нет файла — версия не читается"

# ── проверка целиком ───────────────────────────────────────────────────────────────────
out="$(check_deployed_next_version "$T/app" 2>&1)" && r=0 || r=1
eq "$r" "0" "проверка: версия выше пола — зелёная"
case "$out" in *"16.4.6"*) r=0 ;; *) r=1 ;; esac
eq "$r" "0" "проверка: в строке названа фактическая версия"

# релиз со старой версией — поломка
mkdir -p "$T/old/current/node_modules/next"
printf '{ "name": "next", "version": "16.3.5" }\n' > "$T/old/current/node_modules/next/package.json"
out="$(check_deployed_next_version "$T/old" 2>&1)" && r=0 || r=1
eq "$r" "1" "проверка: версия ниже пола — красная"

# релиз, из которого версию прочитать нечем
mkdir -p "$T/broken/current/node_modules/next"
printf '{ "name": "next" }\n' > "$T/broken/current/node_modules/next/package.json"
out="$(check_deployed_next_version "$T/broken" 2>&1)" && r=0 || r=1
eq "$r" "1" "проверка: версия не читается — красная (тихо не проходим)"

# пол берётся из константы, а не из lockfile: понижение next в package.json не должно
# тихо опустить пол и вернуть дыру незамеченной.
eq "$MIN_NEXT_VERSION" "16.4.1" "пол задан константой: 16.4.1 (первая без advisory)"

if [ "$fail" -ne 0 ]; then
  echo "логика сторожа версии: провалов $fail"
  exit 1
fi
echo "логика сторожа версии: ок"
