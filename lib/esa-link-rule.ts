/**
 * Кому можно привязывать `sub` единого входа к своей учётке — только персоналу.
 *
 * Правило живёт отдельным модулем без единого импорта не из красоты: его спрашивают
 * `npm run check:authz` обычным node, а не бандлером Next, и модуль с графом зависимостей
 * (`oidc-flow` → `oidc` → `sites`) в такую проверку не импортируется.
 *
 * ⚠️ Проверка нужна в ДВУХ местах, и это не дублирование ради вкуса. `start` решает по ней,
 * КАКОЙ режим выдать (`login` посетителю, `link` персоналу), а `callback` — можно ли ветку
 * `link` доиграть. Одной проверки мало: кука прохода живёт 10 минут и переживает понижение
 * роли, а `callback` приводит чужой `sub` к своей учётке, переносит на неё владение
 * карточками и удаляет ту посетительскую оболочку — сырым SQL и с `overrideAccess`.
 * Раньше гейтом там было «есть живая сессия, совпавшая с `flow.userId`», то есть
 * аутентифицирован без роли — ровно то, что мандат brain #015 называет дырой.
 */
export function esaLinkAllowed(role: unknown): boolean {
  return role === "superadmin";
}