/**
 * Может ли этот человек поставить звезду этой карточке — а точнее: это его карточка?
 *
 * Правило живёт отдельным модулем без единого импорта не из красоты: его спрашивает
 * `npm run check:authz` обычным node, а не бандлером Next.
 *
 * ⚠️ Что здесь НЕ закрыто, и об этом надо помнить. Гейт смотрит только на сессию: владелец,
 * который вышел из аккаунта, получает анонимный статус и может поставить звезду своему же
 * бизнесу — ровно как любой посторонний. Иначе пришлось бы требовать вход всем, а это
 * противоречит решению владельца от 2026-09-10: голоса анонимные, «чтобы начать жизнь
 * сайта хотя бы». Закрыт тот случай, который иначе был бы самым заметным: владелец,
 * вошедший в «ПОЗВОНИ», хвалит сам себя из своего же кабинета. Полностью закрыть это
 * без входа нельзя, и честнее сказать об этом, чем делать вид, что закрыто.
 *
 * Значение владельца приходит как `owner_id` (число при `depth: 0`) либо как объект
 * отношения при большей глубине — правило принимает оба вида и молча пропускает всё
 * остальное: лишняя осторожность здесь означала бы тихий запрет голосовать.
 */
export function isOwnCard(owner: unknown, sessionUserId: unknown): boolean {
  const id = (v: unknown): number | null => {
    if (typeof v === "number" && Number.isInteger(v)) return v;
    if (typeof v === "string" && /^\d+$/.test(v)) return Number(v);
    if (v && typeof v === "object" && "id" in v) return id((v as { id: unknown }).id);
    return null;
  };
  const ownerId = id(owner);
  const userId = id(sessionUserId);
  // Нет владельца или нет сессии — это не «оценка себя» (нет владельца роут отбивает
  // раньше, отдельным сообщением про кабинет).
  if (ownerId === null || userId === null) return false;
  return ownerId === userId;
}