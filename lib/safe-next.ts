// Куда возвращать человека после входа.
//
// Правило вынесено в отдельный модуль не ради красоты: `next` приходит из адресной строки,
// то есть целиком подконтролен человеку, и если вернуть его как есть, вход через ЕСА станет
// открытым редиректом. Правило обязано проверяться гейтом, а гейт зовёт настоящие функции —
// поэтому здесь нет ни одного импорта: модуль поднимается обычным node, без сборки и без БД.
//
// Гейт: `npm run check:authz`, секция «После входа нас отправляют только на свой путь».

/** Путь для возврата: относительный, без схемы и хоста — чтобы не стать открытым редиректом. */
export function safeNext(raw: string | null | undefined): string | undefined {
  if (!raw || !raw.startsWith("/") || raw.startsWith("//") || raw.includes("\\")) return undefined;
  return raw.length > 512 ? undefined : raw;
}
